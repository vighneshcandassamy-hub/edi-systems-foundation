from typing import Protocol

from edi.interpret.contracts import Derivation
from edi.world.contracts import WorldCommit, WorldPatch


class DerivationStore(Protocol):
    def find(self, request_id: str, fingerprint: str) -> Derivation | None: ...
    def commit(self, fingerprint: str, derivation: Derivation): ...
    def get(self, derivation_id: str) -> Derivation: ...
    def submission(self, request_id: str, fingerprint: str): ...
    def submission_patch(self, request_id: str, fingerprint: str) -> WorldPatch | None: ...
    def prepare_submission(self, request_id: str, fingerprint: str, patch: WorldPatch) -> WorldPatch: ...
    def record_submission(self, request_id: str, fingerprint: str, result: WorldCommit): ...


class CandidateWorldPort(Protocol):
    def propose_patch(self, patch: WorldPatch) -> WorldCommit: ...
    def commit_status(self, request_id: str) -> WorldCommit | None: ...
